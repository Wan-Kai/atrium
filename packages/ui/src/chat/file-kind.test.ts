import { describe, expect, it } from "vitest";
import { fileKind } from "./file-kind";

describe("fileKind", () => {
  it.each([
    ["src/a.ts", "ts"],
    ["a.mts", "ts"],
    ["a.cts", "ts"],
    ["src/App.tsx", "react"],
    ["a.jsx", "react"],
    ["a.js", "js"],
    ["a.mjs", "js"],
    ["a.cjs", "js"],
    ["apps/web/package.json", "npm"],
    ["tsconfig.json", "json"],
    ["a.jsonc", "json"],
    ["a.json5", "json"],
    ["README.md", "md"],
    ["a.mdx", "md"],
    ["a.markdown", "md"],
    ["a.css", "css"],
    ["a.scss", "css"],
    ["a.sass", "css"],
    ["a.less", "css"],
    ["index.html", "html"],
    ["a.htm", "html"],
    ["main.py", "py"],
    ["a.pyi", "py"],
    ["lib.rs", "rs"],
    ["main.go", "go"],
    ["build.sh", "sh"],
    ["a.bash", "sh"],
    ["a.zsh", "sh"],
    ["a.fish", "sh"],
    ["Main.java", "java"],
    ["a.kt", "kotlin"],
    ["build.gradle.kts", "kotlin"],
    ["a.swift", "swift"],
    ["a.php", "php"],
    ["a.dart", "dart"],
    ["a.c", "c"],
    ["a.h", "c"],
    ["a.cc", "c"],
    ["a.cpp", "c"],
    ["a.cxx", "c"],
    ["a.hpp", "c"],
    ["App.vue", "vue"],
    ["Dockerfile", "docker"],
    ["Dockerfile.dev", "docker"],
    ["web.dockerfile", "docker"],
    ["a.sql", "sql"],
    ["a.png", "image"],
    ["a.jpg", "image"],
    ["a.jpeg", "image"],
    ["a.gif", "image"],
    ["a.webp", "image"],
    ["favicon.ico", "image"],
    ["a.bmp", "image"],
    ["a.avif", "image"],
    ["logo.svg", "svg"],
    ["a.pdf", "pdf"],
    ["a.csv", "csv"],
    ["a.tsv", "csv"],
    ["a.xml", "xml"],
    [".gitignore", "git"],
    ["sub/.gitattributes", "git"],
    [".gitmodules", "git"],
    ["pnpm-lock.yaml", "lock"],
    ["package-lock.json", "lock"],
    ["Cargo.lock", "lock"],
    [".env", "config"],
    [".env.local", "config"],
    ["a.yml", "config"],
    ["a.yaml", "config"],
    ["a.toml", "config"],
    ["a.ini", "config"],
    ["a.conf", "config"],
    ["a.cfg", "config"],
    ["a.properties", "config"],
    ["notes.txt", "text"],
    ["a.log", "text"],
    ["a.zip", "archive"],
    ["a.tar", "archive"],
    ["a.tar.gz", "archive"],
    ["a.tgz", "archive"],
    ["a.7z", "archive"],
    ["a.rar", "archive"],
  ])("knows %s as %s", (path, kind) => {
    expect(fileKind(path)).toBe(kind);
  });

  it.each([
    ["capitals", "SRC/README.MD", "md"],
    ["a capital file name", "PACKAGE.JSON", "npm"],
    ["a lower-case Dockerfile", "dockerfile", "docker"],
    ["a directory that looks like a type", "src.ts/notes", "file"],
    ["a dot file of no known kind", ".prettierrc", "file"],
    ["no extension", "Makefile", "file"],
    ["an unknown extension", "a.xyz", "file"],
    ["a name ending in a dot", "a.", "file"],
    ["an empty path", "", "file"],
    ["a name that only contains a known one", "my-package.json", "json"],
    ["an env-like name", ".envrc", "file"],
    ["a Dockerfile-like name", "Dockerfiles", "file"],
    ["a name with no dot that is an extension", "bin/go", "file"],
    ["a name starting with its only dot", ".json", "file"],
  ])("reads %s", (_case, path, kind) => {
    expect(fileKind(path)).toBe(kind);
  });
});
