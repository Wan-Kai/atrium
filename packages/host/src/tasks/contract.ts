import { activeGraphOf, downstreamOf, latestRun, reachableFrom, topologicalOrder, upstreamOf } from "./graph";
import { escapeShell, firstSentence, quoted } from "./quote";
import { RESUME_GRAPH_APPROVED } from "./texts";
import type { GraphNode, GraphVersion, NodeId, NodeRun, Task } from "./types";

/*
 * The first message of a node (SPEC-0006, "第一条消息：契约"). Words for the model, not for the user
 * (coding-standards.md, "宿主不产出给用户看的文字"); the wording is SPEC-0006's.
 */

/** Where a node stands in the list of the whole graph, from its own point of view. */
type Standing = "passed" | "you" | "next" | "later" | "user";

/**
 * Where each node stands for one node.
 *
 * @remarks
 * `✓ 已通过` when it has passed, `← 你` for the node itself, `由用户决定` for a human node that has not
 * passed, `下一步` for what follows the node directly, and `之后` for the rest.
 *
 * @sideEffects none
 * @param task - The task.
 * @param graph - The graph in force.
 * @param self - The node the contract is for.
 * @returns The standing of every node, by id.
 */
function standings(task: Task, graph: GraphVersion, self: GraphNode): Map<NodeId, Standing> {
  const direct = new Set(downstreamOf(graph, self.id));
  const result = new Map<NodeId, Standing>();
  for (const node of graph.nodes) {
    const passed = latestRun(task, node.id)?.state === "passed" && latestRun(task, node.id)?.void !== true;
    let standing: Standing = "later";
    if (node.id === self.id) standing = "you";
    else if (passed) standing = "passed";
    else if (node.kind === "human") standing = "user";
    else if (direct.has(node.id)) standing = "next";
    result.set(node.id, standing);
  }
  return result;
}

/** The words for each standing. */
const STANDING_WORDS: Readonly<Record<Standing, string>> = {
  passed: "✓ 已通过",
  you: "← 你",
  next: "下一步",
  later: "之后",
  user: "由用户决定",
};

/**
 * The whole graph as a list, topological, with where the node is.
 *
 * @remarks
 * Computed from the graph, not generated by the model (SPEC-0006, "第一条消息：契约").
 *
 * @sideEffects none
 * @param task - The task.
 * @param graph - The graph in force.
 * @param self - The node the contract is for.
 * @returns One line per node.
 */
function graphLines(task: Task, graph: GraphVersion, self: GraphNode): string[] {
  const where = standings(task, graph, self);
  return topologicalOrder(graph).flatMap((id) => {
    const node = graph.nodes.find((candidate) => candidate.id === id);
    const standing = where.get(id);
    return node === undefined || standing === undefined
      ? []
      : [`  - ${escapeShell(node.id)} · ${escapeShell(node.name)}：${STANDING_WORDS[standing]}`];
  });
}

/**
 * The nodes that come after a node, with what each does in a sentence.
 *
 * @remarks
 * "不归你做的": every node reachable from it, human nodes included, from the graph.
 *
 * @sideEffects none
 * @param graph - The graph in force.
 * @param self - The node.
 * @returns One line per node that follows.
 */
function notYours(graph: GraphVersion, self: GraphNode): string[] {
  const after = reachableFrom(graph, self.id);
  after.delete(self.id);
  return topologicalOrder(graph).flatMap((id) => {
    const node = graph.nodes.find((candidate) => candidate.id === id);
    return node === undefined || !after.has(id)
      ? []
      : [`  - ${escapeShell(node.name)} · ${escapeShell(firstSentence(node.job))}`];
  });
}

/**
 * The summary of the latest run of a node that passed.
 *
 * @remarks
 * Downstream nodes read only the latest pass, so a branch a send-back reset does not hand over an old
 * summary (SPEC-0006, "调度器 · 打回").
 *
 * @sideEffects none
 * @param task - The task.
 * @param node - The node.
 * @returns The run, or `undefined`.
 */
function latestPassed(task: Task, node: NodeId): NodeRun | undefined {
  return task.runs.findLast((run) => run.node === node && run.state === "passed" && run.void !== true);
}

/**
 * What a node reads as its input: the summaries of the nodes named in `inputs`, or of all direct upstream.
 *
 * @remarks
 * Each is quoted as data from the node that wrote it (ADR-0013, point 10).
 *
 * @sideEffects none
 * @param task - The task.
 * @param graph - The graph in force.
 * @param node - The node.
 * @returns The quoted summaries, empty when there are none.
 */
function inputsOf(task: Task, graph: GraphVersion, node: GraphNode): string[] {
  const sources = node.inputs ?? upstreamOf(graph, node.id);
  return sources.flatMap((id) => {
    const source = graph.nodes.find((candidate) => candidate.id === id);
    const summary = latestPassed(task, id)?.summary;
    return source === undefined || summary === undefined || summary === null
      ? []
      : [quoted(`${source.id} · ${source.name}`, summary)];
  });
}

/** What the contract needs beyond the task. */
export interface ContractInput {
  readonly task: Task;
  readonly node: GraphNode;
  /** The run the contract is for. */
  readonly run: NodeRun;
  /** The worktree was just made and has no dependencies installed (SPEC-0006, "第一条消息：契约"). */
  readonly freshWorktree: boolean;
}

/**
 * Builds the first message of a node.
 *
 * @remarks
 * SPEC-0006, "第一条消息：契约", in the order given there. The goal, every summary and the send-back reason
 * come from models and are quoted and escaped; the names and jobs of the graph are the task conversation's
 * writing and are escaped. After a send-back (`attempt > 1`) the node's earlier summary and commit are
 * included.
 *
 * @sideEffects none
 * @param input - The task, the node, its run and whether the worktree is new.
 * @returns The message, wrapped in `<atrium-task-node>`.
 * @throws {Error} When the task has no graph in force.
 */
export function buildContract(input: ContractInput): string {
  const { task, node, run, freshWorktree } = input;
  const graph = activeGraphOf(task);
  if (graph === undefined) throw new Error("the task has no graph in force");
  const next = downstreamOf(graph, node.id)
    .map((id) => graph.nodes.find((candidate) => candidate.id === id)?.name)
    .filter((name): name is string => name !== undefined)
    .map((name) => escapeShell(name));
  const lines: string[] = [
    "<atrium-task-node>",
    `你在任务「${escapeShell(task.name)}」里负责节点 ${escapeShell(node.id)} · ${escapeShell(node.name)}。`,
    "",
    `【任务目标】${quoted("任务对话", task.summary.goal)}`,
    ...(task.summary.decisions.length === 0
      ? []
      : [`【已定结论】${quoted("任务对话", task.summary.decisions.join("\n"))}`]),
    "【整张图，你在这里】",
    ...graphLines(task, graph, node),
    `【你这一步要做的】${escapeShell(node.job)}`,
    "【做到这样就算完成】",
    ...node.done.map((line) => `  - ${escapeShell(line)}`),
    "【不归你做的】后面节点的事，不要提前做：",
    ...notYours(graph, node),
  ];
  const inputs = inputsOf(task, graph, node);
  if (inputs.length > 0) lines.push("【输入】", ...inputs);
  if (freshWorktree && node.role === "work") {
    lines.push("【环境】这是新建的 worktree，还没有装依赖，先按项目说明装好。");
  }
  if (run.attempt > 1 && run.backFrom !== undefined) {
    lines.push(
      `【上次被打回的原因】${quoted(run.backFrom.node, run.backFrom.reason)}（来自 ${escapeShell(run.backFrom.node)}）`,
    );
  }
  const earlier = task.runs.findLast(
    (candidate) => candidate.node === node.id && candidate.attempt < run.attempt && candidate.summary !== null,
  );
  if (earlier?.summary !== undefined && earlier.summary !== null) {
    lines.push(
      `【你上一次的交接摘要】${quoted(`${node.id} · ${node.name}`, earlier.summary)}${
        earlier.commit === null ? "" : `，当时结束在提交 ${escapeShell(earlier.commit)}`
      }；worktree 里保留着那次的改动。`,
    );
  }
  lines.push(
    "",
    "做完单独调用 node_done，把交接摘要写进 summary：做了什么；产出在哪；「怎样算完成」逐条的结果；",
    `留给下游、你没做的；风险和拿不准的地方。下一步是 ${next.length === 0 ? "（没有，你是最后一步）" : next.join("、")}。`,
    "不做后面的事就完不成时，调用 request_graph_change；拿不准时用 ask_user 问用户，不要猜。",
    "</atrium-task-node>",
  );
  return lines.join("\n");
}

/**
 * The text a node gets when its graph change is approved: the line, then the new graph and what is not its.
 *
 * @remarks
 * SPEC-0006, "中途": "图已改，下面是新的契约", with the new "不归你做的". The standings and the list come from
 * the graph in force, as at the start.
 *
 * @sideEffects none
 * @param task - The task, with the new graph in force.
 * @param node - The node that asked.
 * @returns The text, or just the line when the node is no longer in the graph.
 */
export function graphChangedText(task: Task, node: NodeId): string {
  const graph = activeGraphOf(task);
  const self = graph?.nodes.find((candidate) => candidate.id === node);
  if (graph === undefined || self === undefined) return RESUME_GRAPH_APPROVED;
  return [
    RESUME_GRAPH_APPROVED,
    "【整张图，你在这里】",
    ...graphLines(task, graph, self),
    "【不归你做的】后面节点的事，不要提前做：",
    ...notYours(graph, self),
  ].join("\n");
}
