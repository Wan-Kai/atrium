/** A JSON key that can be a Swift property name as it is. */
const IDENTIFIER = /^[A-Za-z_][A-Za-z0-9_]*$/u;

/**
 * Generates Swift source for a bundle of named schemas.
 *
 * @remarks
 * Each named schema becomes one top-level declaration: a `struct` for an object, an `enum` for a
 * string enum or a union, a `typealias` for anything else. Inline objects, enums and unions become
 * types nested in the type that uses them. See testing.md for how each construct maps.
 *
 * @sideEffects none
 * @param {{ protocolVersion: number, schemas: Record<string, any>, commandResults?: Record<string, string> }} bundle -
 *   The protocol version, the schemas by name and each command's result schema, as
 *   `protocolJsonSchema()` returns them.
 * @param {{ caseNames?: Record<string, Record<string, string>> }} [options] - `caseNames` names
 *   the cases of unions told apart by a boolean, by union and value (`{ true: "success" }`).
 * @returns {string} The Swift source.
 * @throws {Error} `<place>: <why>` for a construct the generator does not support.
 */
export function generateSwift(bundle, options = {}) {
  const ctx = {
    schemas: bundle.schemas,
    caseNames: options.caseNames ?? {},
    top: new Set(Object.keys(bundle.schemas)),
  };
  const blocks = Object.keys(bundle.schemas)
    .toSorted()
    .map((name) => declareTop(ctx, name).join("\n"));
  return [
    "// Generated by `pnpm protocol:swift` from packages/protocol (ADR-0015). Do not edit.",
    "// swift-format-ignore-file",
    `// Schema SHA-256: ${fingerprint(bundle)}`,
    "",
    "/// The wire protocol version these types were generated from.",
    `public let protocolVersion = ${bundle.protocolVersion}`,
    "",
    blocks.join("\n\n"),
    ...resultLookup(ctx, bundle.commandResults ?? {}),
    "",
  ].join("\n");
}

/**
 * Writes the function that gives the Swift type of each command's result.
 *
 * @remarks
 * A response carries `result` as open JSON (SPEC-0001 "应答"); the client knows which command it
 * sent, and this tells it which type to decode the result as. Commands in name order.
 *
 * @sideEffects none
 * @param {any} ctx - The run.
 * @param {Record<string, string>} results - The result schema's name, by command type.
 * @returns {string[]} The lines, with a blank line before; none when there are no results.
 * @throws {Error} When a result names a schema that is not in the bundle.
 */
function resultLookup(ctx, results) {
  const commands = Object.keys(results).toSorted();
  if (commands.length === 0) return [];
  const cases = commands.map((command) => {
    const name = results[command];
    if (!ctx.top.has(name)) throw fail(`#/commandResults/${command}`, `unknown result type ${name}`);
    return `  case ${literal(command)}: ${name}.self`;
  });
  return [
    "",
    "/// The Swift type of a command's result, by the command's `type`; `nil` for an unknown command.",
    "public func commandResultType(_ command: String) -> (any Codable.Type)? {",
    "  switch command {",
    ...cases,
    "  default: nil",
    "  }",
    "}",
  ];
}

/**
 * Hashes the whole bundle, keys sorted, so the generated file changes with any change to the schemas.
 *
 * @remarks
 * Swift does not check lengths, ranges or patterns, so a change to one of them alone generates the
 * same Swift; `--check` would pass while the fixtures and the host disagree with what was
 * reviewed. The hash puts every change into the file (testing.md, "协议类型的生成与往返测试").
 *
 * @sideEffects none
 * @param {unknown} bundle - What `generateSwift` was given.
 * @returns {string} The SHA-256 of its normalised JSON, in hex.
 */
function fingerprint(bundle) {
  return createHash("sha256")
    .update(JSON.stringify(sortKeys(bundle)))
    .digest("hex");
}

/**
 * Copies a JSON value with every object's keys in order.
 *
 * @remarks
 * Key order carries no meaning in JSON Schema, so it must not change the fingerprint.
 *
 * @sideEffects none
 * @param {unknown} value - The value.
 * @returns {unknown} The copy.
 */
function sortKeys(value) {
  if (Array.isArray(value)) return value.map(sortKeys);
  if (typeof value !== "object" || value === null) return value;
  return Object.fromEntries(
    Object.keys(value)
      .toSorted()
      .map((key) => [key, sortKeys(value[key])]),
  );
}

/**
 * Makes the error for an unsupported construct.
 *
 * @remarks
 * Every refusal names its place as a JSON pointer into the bundle, so it can be found in zod.
 *
 * @sideEffects none
 * @param {string} path - Where in the bundle, `#/<name>/…`.
 * @param {string} why - What is wrong.
 * @returns {Error} The error to throw.
 */
function fail(path, why) {
  return new Error(`${path}: ${why}`);
}

/**
 * Refuses a schema with keys the generator does not understand.
 *
 * @remarks
 * Run on every schema before it is read, so `allOf`, tuples and the like are never skipped silently.
 *
 * @sideEffects none
 * @param {unknown} schema - The schema.
 * @param {string} path - Its place.
 * @throws {Error} When it is not an object or has an unknown key.
 */
function check(schema, path) {
  if (typeof schema !== "object" || schema === null || Array.isArray(schema)) throw fail(path, "not a schema");
  for (const key of Object.keys(schema)) {
    if (!KNOWN_KEYS.has(key)) throw fail(path, `unsupported schema (${key})`);
  }
}

/**
 * Tells whether a schema is exactly JSON `null`.
 *
 * @remarks
 * zod writes `.nullable()` as a union with this member.
 *
 * @sideEffects none
 * @param {any} schema - The schema.
 * @returns {boolean} Whether it only allows `null`.
 */
function isNull(schema) {
  return schema.type === "null";
}

/**
 * Splits a schema into the part that is not `null` and whether `null` is allowed.
 *
 * @remarks
 * Nullability is carried by the field that uses a type, not by the type, so `T | null` becomes
 * a field of type `T?`.
 *
 * @sideEffects none
 * @param {any} raw - The schema.
 * @param {string} path - Its place.
 * @returns {{ schema: any, nullable: boolean, path: string }} The rest, whether `null` was allowed,
 *   and the rest's place.
 */
function stripNull(raw, path) {
  if (Array.isArray(raw.type) && raw.type.includes("null")) {
    const rest = raw.type.filter((type) => type !== "null");
    return { schema: { ...raw, type: rest.length === 1 ? rest[0] : rest }, nullable: true, path };
  }
  for (const key of ["anyOf", "oneOf"]) {
    const members = raw[key];
    if (!Array.isArray(members) || !members.some(isNull)) continue;
    const rest = members.map((member, index) => ({ member, index })).filter(({ member }) => !isNull(member));
    const [only] = rest;
    if (rest.length === 1 && only !== undefined) {
      return { schema: only.member, nullable: true, path: `${path}/${key}/${only.index}` };
    }
    return { schema: { ...raw, [key]: rest.map(({ member }) => member) }, nullable: true, path };
  }
  return { schema: raw, nullable: false, path };
}

/**
 * Looks up a referenced schema.
 *
 * @remarks
 * References are by name within the bundle (`protocolJsonSchema` sets them so).
 *
 * @sideEffects none
 * @param {any} ctx - The run.
 * @param {string} name - The referenced name.
 * @param {string} path - Where the reference is.
 * @returns {any} The schema.
 * @throws {Error} When no schema has that name.
 */
function resolve(ctx, name, path) {
  const target = ctx.schemas[name];
  if (target === undefined) throw fail(path, `unknown reference ${name}`);
  return target;
}

/**
 * Tells whether a schema only ever holds a string with no fixed values.
 *
 * @remarks
 * Branded ids and unions of them (`ContainerId`) are plain strings in Swift.
 *
 * @sideEffects none
 * @param {any} ctx - The run.
 * @param {any} schema - The schema.
 * @returns {boolean} Whether it is a plain string.
 */
function isPlainString(ctx, schema) {
  if (typeof schema.$ref === "string") {
    const target = ctx.schemas[schema.$ref];
    return target !== undefined && isPlainString(ctx, target);
  }
  const members = schema.anyOf ?? schema.oneOf;
  if (Array.isArray(members)) return members.length > 0 && members.every((member) => isPlainString(ctx, member));
  return schema.type === "string" && !("enum" in schema) && !("const" in schema);
}

/**
 * Tells whether a schema is open JSON: no type, reference, union or fixed values.
 *
 * @remarks
 * zod writes `z.unknown()` as `{}`.
 *
 * @sideEffects none
 * @param {any} schema - The schema.
 * @returns {boolean} Whether any JSON value fits.
 */
function isOpen(schema) {
  return ["type", "$ref", "anyOf", "oneOf", "enum", "const"].every((key) => !(key in schema));
}

/**
 * Makes a fresh naming scope for the types nested in one declaration.
 *
 * @remarks
 * A nested name must not hide an enclosing type's name.
 *
 * @sideEffects none
 * @param {Set<string>} ancestors - The names of the enclosing types.
 * @returns {{ ancestors: Set<string>, used: Set<string>, nested: string[][] }} The scope.
 */
function newScope(ancestors) {
  return { ancestors, used: new Set(), nested: [] };
}

/**
 * Picks a name for a nested type that hides nothing.
 *
 * @remarks
 * A nested type named like a top-level type would hide it from the code around it (a field
 * `step` of top-level type `Step`); such names get `Value` appended, then a number.
 *
 * @sideEffects Marks the name as used in the scope.
 * @param {any} ctx - The run.
 * @param {{ ancestors: Set<string>, used: Set<string> }} scope - Where the type goes.
 * @param {string} base - The name it would like.
 * @returns {string} The name.
 */
function nestedName(ctx, scope, base) {
  let name = isTaken(ctx, scope, base) ? `${base}Value` : base;
  for (let index = 2; isTaken(ctx, scope, name); index += 1) name = `${base}Value${index}`;
  scope.used.add(name);
  return name;
}

/**
 * Tells whether a nested type's name would hide another type or is already used.
 *
 * @remarks
 * See `nestedName`.
 *
 * @sideEffects none
 * @param {any} ctx - The run.
 * @param {{ ancestors: Set<string>, used: Set<string> }} scope - Where the type goes.
 * @param {string} name - The name.
 * @returns {boolean} Whether it is taken.
 */
function isTaken(ctx, scope, name) {
  return ctx.top.has(name) || RESERVED_TYPES.has(name) || scope.ancestors.has(name) || scope.used.has(name);
}

/**
 * Writes one top-level declaration.
 *
 * @remarks
 * See `generateSwift`.
 *
 * @sideEffects none
 * @param {any} ctx - The run.
 * @param {string} name - The schema's name.
 * @returns {string[]} The declaration's lines.
 */
function declareTop(ctx, name) {
  const raw = ctx.schemas[name];
  check(raw, `#/${name}`);
  const { schema, path } = stripNull(raw, `#/${name}`);
  check(schema, path);
  if (schema.anyOf !== undefined || schema.oneOf !== undefined) {
    if (isPlainString(ctx, schema)) return [`public typealias ${name} = String`];
    return declareUnion(ctx, name, schema, path, new Set());
  }
  if (schema.type === "string" && Array.isArray(schema.enum)) return declareStringEnum(name, schema, path);
  if (schema.type === "object" && !isRecord(schema)) return declareStruct(ctx, name, schema, path, new Set());
  const scope = newScope(new Set([name]));
  const type = typeFor(ctx, schema, path, scope, name);
  if (scope.nested.length > 0) throw fail(path, "unsupported inline type in an alias");
  return [`public typealias ${name} = ${type.swift}`];
}

/**
 * Tells whether an object schema is a record: no named properties, values of one schema.
 *
 * @remarks
 * zod writes `z.record` this way.
 *
 * @sideEffects none
 * @param {any} schema - An object schema.
 * @returns {boolean} Whether it is a record.
 */
function isRecord(schema) {
  return schema.properties === undefined && typeof schema.additionalProperties === "object";
}

/**
 * Works out the Swift type of a field, array item or record value.
 *
 * @remarks
 * Inline objects, enums and unions are declared in `scope` and named from `hint`.
 *
 * @sideEffects Adds nested declarations to `scope`.
 * @param {any} ctx - The run.
 * @param {any} raw - The schema.
 * @param {string} path - Its place.
 * @param {{ ancestors: Set<string>, used: Set<string>, nested: string[][] }} scope - Where nested types go.
 * @param {string} hint - The name a nested type would like.
 * @returns {{ swift: string, nullable: boolean }} The type, and whether `null` is allowed.
 */
function typeFor(ctx, raw, path, scope, hint) {
  check(raw, path);
  const { schema, nullable, path: at } = stripNull(raw, path);
  check(schema, at);
  const type = baseType(ctx, schema, at, scope, hint);
  return { swift: type.swift, nullable: nullable || type.nullable };
}

/**
 * Works out the Swift type of a schema that is not a union with `null`.
 *
 * @remarks
 * See `typeFor`. A reference carries the nullability of the schema it names (`ContextReserve`).
 *
 * @sideEffects Adds nested declarations to `scope`.
 * @param {any} ctx - The run.
 * @param {any} schema - The schema.
 * @param {string} path - Its place.
 * @param {{ ancestors: Set<string>, used: Set<string>, nested: string[][] }} scope - Where nested types go.
 * @param {string} hint - The name a nested type would like.
 * @returns {{ swift: string, nullable: boolean }} The type, and whether `null` is allowed.
 * @throws {Error} For a constant, an unknown reference or an unsupported type.
 */
function baseType(ctx, schema, path, scope, hint) {
  if (typeof schema.$ref === "string") {
    const target = resolve(ctx, schema.$ref, path);
    return { swift: schema.$ref, nullable: stripNull(target, path).nullable };
  }
  if ("const" in schema) throw fail(path, `unsupported constant ${JSON.stringify(schema.const)}`);
  if (isOpen(schema) || Array.isArray(schema.type)) return { swift: "JSONValue", nullable: false };
  if (schema.anyOf !== undefined || schema.oneOf !== undefined) {
    if (isPlainString(ctx, schema)) return { swift: "String", nullable: false };
    const name = nestedName(ctx, scope, hint);
    scope.nested.push(declareUnion(ctx, name, schema, path, scope.ancestors));
    return { swift: name, nullable: false };
  }
  switch (schema.type) {
    case "string": {
      if (!Array.isArray(schema.enum)) return { swift: "String", nullable: false };
      const name = nestedName(ctx, scope, hint);
      scope.nested.push(declareStringEnum(name, schema, path));
      return { swift: name, nullable: false };
    }
    case "integer":
      return { swift: "Int", nullable: false };
    case "number":
      return { swift: "Double", nullable: false };
    case "boolean":
      return { swift: "Bool", nullable: false };
    case "array": {
      if (schema.items === undefined) throw fail(path, "array without items");
      const item = typeFor(ctx, schema.items, `${path}/items`, scope, singular(hint));
      return { swift: `[${item.swift}${item.nullable ? "?" : ""}]`, nullable: false };
    }
    case "object": {
      if (isRecord(schema)) {
        const value = typeFor(ctx, schema.additionalProperties, `${path}/additionalProperties`, scope, singular(hint));
        return { swift: `[String: ${value.swift}${value.nullable ? "?" : ""}]`, nullable: false };
      }
      const name = nestedName(ctx, scope, hint);
      scope.nested.push(declareStruct(ctx, name, schema, path, scope.ancestors));
      return { swift: name, nullable: false };
    }
    default:
      throw fail(path, `unsupported type ${JSON.stringify(schema.type)}`);
  }
}

/**
 * Names an array's item type after the array.
 *
 * @remarks
 * `windows: [Window]` reads better than `windows: [WindowsItem]`.
 *
 * @sideEffects none
 * @param {string} name - The array's type name.
 * @returns {string} The item's.
 */
function singular(name) {
  if (name.endsWith("ies")) return `${name.slice(0, -3)}y`;
  if (name.endsWith("s") && !name.endsWith("ss")) return name.slice(0, -1);
  return `${name}Item`;
}

/**
 * Writes an object schema as a `struct` with its own `Codable` code.
 *
 * @remarks
 * Required constant fields are checked when decoding and written when encoding, but not stored;
 * an optional one is stored as an optional value that must be the constant when present, both when
 * decoding and when encoding. Required,
 * nullable and omittable fields each decode differently (`CodingSupport.swift`), so a host that
 * sends `null` where the schema forbids it is noticed.
 *
 * @sideEffects none
 * @param {any} ctx - The run.
 * @param {string} name - The type's name.
 * @param {any} schema - The object schema.
 * @param {string} path - Its place.
 * @param {Set<string>} ancestors - The enclosing types' names.
 * @returns {string[]} The declaration's lines.
 * @throws {Error} For a key that is not a Swift name, or an unsupported constant.
 */
function declareStruct(ctx, name, schema, path, ancestors) {
  const scope = newScope(new Set([...ancestors, name]));
  const required = new Set(schema.required ?? []);
  const fields = [];
  const constants = [];
  for (const [key, property] of Object.entries(schema.properties ?? {})) {
    const at = `${path}/properties/${key}`;
    if (!IDENTIFIER.test(key)) throw fail(at, `key ${JSON.stringify(key)} is not a Swift name`);
    check(property, at);
    if ("const" in property) {
      const value = constant(property.const, at);
      if (required.has(key)) {
        constants.push({ key, value });
      } else {
        const swift = typeof property.const === "boolean" ? "Bool" : "String";
        fields.push({ key, name: escape(key), swift, nullable: false, optional: true, constant: value });
      }
      continue;
    }
    const type = typeFor(ctx, property, at, scope, upperFirst(key));
    fields.push({ key, name: escape(key), swift: type.swift, nullable: type.nullable, optional: !required.has(key) });
  }
  const lines = [`public struct ${name}: Codable, Sendable, Equatable {`];
  for (const field of fields) lines.push(`  public var ${field.name}: ${declared(field)}`);
  if (fields.length > 0) lines.push("");
  for (const block of scope.nested) lines.push(...indent(block), "");
  if (fields.length === 0) {
    lines.push("  public init() {}");
  } else {
    lines.push(
      "  public init(",
      fields.map((field) => `    ${field.name}: ${declared(field)}${field.optional ? " = nil" : ""}`).join(",\n"),
      "  ) {",
      ...fields.map((field) => `    self.${field.name} = ${field.name}`),
      "  }",
    );
  }
  const empty = fields.length === 0 && constants.length === 0;
  lines.push(
    "",
    "  public init(from decoder: any Decoder) throws {",
    empty
      ? "    _ = try decoder.container(keyedBy: AnyKey.self)"
      : "    let container = try decoder.container(keyedBy: AnyKey.self)",
    ...constants.map(({ key, value }) => `    try container.expect(${literal(key)}, ${value})`),
    ...fields.map((field) =>
      field.constant === undefined
        ? `    self.${field.name} = try container.${decodeMethod(field)}(${field.swift}.self, forKey: ${literal(field.key)})`
        : `    self.${field.name} = try container.decodeOmittableConstant(${field.constant}, forKey: ${literal(field.key)})`,
    ),
    "  }",
    "",
    "  public func encode(to encoder: any Encoder) throws {",
    empty
      ? "    _ = encoder.container(keyedBy: AnyKey.self)"
      : "    var container = encoder.container(keyedBy: AnyKey.self)",
    ...constants.map(({ key, value }) => `    try container.encode(${value}, forKey: ${literal(key)})`),
    ...fields.map((field) =>
      field.constant === undefined
        ? `    try container.${encodeMethod(field)}(self.${field.name}, forKey: ${literal(field.key)})`
        : `    try container.encodeOmittableConstant(self.${field.name}, ${field.constant}, forKey: ${literal(field.key)})`,
    ),
    "  }",
    "}",
  );
  return lines;
}

/**
 * Writes a constant as a Swift literal.
 *
 * @remarks
 * Only strings and booleans appear as constants in the protocol.
 *
 * @sideEffects none
 * @param {unknown} value - The constant.
 * @param {string} path - Its place.
 * @returns {string} The literal.
 * @throws {Error} For any other kind of constant.
 */
function constant(value, path) {
  if (typeof value === "string") return literal(value);
  if (typeof value === "boolean") return String(value);
  throw fail(path, `unsupported constant ${JSON.stringify(value)}`);
}

/**
 * Says the Swift type a field is declared with.
 *
 * @remarks
 * A field both omittable and nullable keeps the two apart with `Nullable` (see its doc comment).
 *
 * @sideEffects none
 * @param {{ swift: string, nullable: boolean, optional: boolean }} field - The field.
 * @returns {string} Its declared type.
 */
function declared(field) {
  if (field.optional && field.nullable) return `Nullable<${field.swift}>?`;
  if (field.optional || field.nullable) return `${field.swift}?`;
  return field.swift;
}

/**
 * Picks the decoding method for a field.
 *
 * @remarks
 * See `declareStruct`.
 *
 * @sideEffects none
 * @param {{ nullable: boolean, optional: boolean }} field - The field.
 * @returns {string} The method's name.
 */
function decodeMethod(field) {
  if (field.optional) return field.nullable ? "decodeOmittableNullable" : "decodeOmittable";
  return field.nullable ? "decodeNullable" : "decode";
}

/**
 * Picks the encoding method for a field.
 *
 * @remarks
 * Paired with `decodeMethod`.
 *
 * @sideEffects none
 * @param {{ nullable: boolean, optional: boolean }} field - The field.
 * @returns {string} The method's name.
 */
function encodeMethod(field) {
  if (field.optional) return field.nullable ? "encodeOmittableNullable" : "encodeIfPresent";
  return field.nullable ? "encodeNullable" : "encode";
}

/**
 * Writes a string enum as a Swift `enum` backed by `String`.
 *
 * @remarks
 * Case names are lower camel case; values that differ from their case name keep them as raw values.
 *
 * @sideEffects none
 * @param {string} name - The type's name.
 * @param {any} schema - The schema.
 * @param {string} path - Its place.
 * @returns {string[]} The declaration's lines.
 * @throws {Error} For a value that is not a string, or two values with the same case name.
 */
function declareStringEnum(name, schema, path) {
  const lines = [`public enum ${name}: String, Codable, Sendable, Equatable, CaseIterable {`];
  const seen = new Set();
  for (const value of schema.enum) {
    if (typeof value !== "string") throw fail(path, `unsupported enum value ${JSON.stringify(value)}`);
    const caseName = camel(value, path);
    if (seen.has(caseName)) throw fail(path, `two values are both case ${caseName}`);
    seen.add(caseName);
    lines.push(`  case ${escape(caseName)}${caseName === value ? "" : ` = ${literal(value)}`}`);
  }
  lines.push("}");
  return lines;
}

/**
 * Writes a union as a Swift `enum`.
 *
 * @remarks
 * Unions of scalars are told apart by their kind; unions of objects by a discriminating field
 * if one exists, else by a key only one member has (testing.md).
 *
 * @sideEffects none
 * @param {any} ctx - The run.
 * @param {string} name - The type's name.
 * @param {any} schema - The union schema, without `null`.
 * @param {string} path - Its place.
 * @param {Set<string>} ancestors - The enclosing types' names.
 * @returns {string[]} The declaration's lines.
 */
function declareUnion(ctx, name, schema, path, ancestors) {
  const key = schema.anyOf === undefined ? "oneOf" : "anyOf";
  const members = schema[key].map((member, index) => ({ schema: member, path: `${path}/${key}/${index}` }));
  for (const member of members) check(member.schema, member.path);
  if (members.every((member) => isScalar(member.schema))) return declareScalarUnion(name, members);
  const discriminator = findDiscriminator(ctx, members);
  if (discriminator !== null) return declareTagged(ctx, name, members, discriminator, ancestors);
  return declareUntagged(ctx, name, members, path, ancestors);
}

/**
 * Tells whether a union member is an inline scalar or a constant.
 *
 * @remarks
 * `ContextReserve` is a count or `"off"`.
 *
 * @sideEffects none
 * @param {any} schema - The member.
 * @returns {boolean} Whether it is a scalar.
 */
function isScalar(schema) {
  if ("const" in schema) return typeof schema.const === "string";
  return ["string", "integer", "number", "boolean"].includes(schema.type) && !("enum" in schema);
}

/**
 * Writes a union of scalars, decoded by trying each kind.
 *
 * @remarks
 * Constants are tried first, so `"off"` is not read as any string.
 *
 * @sideEffects none
 * @param {string} name - The type's name.
 * @param {Array<{ schema: any, path: string }>} members - The members.
 * @returns {string[]} The declaration's lines.
 * @throws {Error} When two members would be the same case.
 */
function declareScalarUnion(name, members) {
  const kinds = {
    boolean: ["bool", "Bool"],
    integer: ["int", "Int"],
    number: ["double", "Double"],
    string: ["string", "String"],
  };
  const cases = members.map(({ schema, path }) =>
    "const" in schema
      ? { name: camel(schema.const, path), value: schema.const, path }
      : { name: kinds[schema.type][0], swift: kinds[schema.type][1], path },
  );
  assertDistinct(cases);
  const order = ["Bool", "Int", "Double", "String"];
  const tried = [
    ...cases.filter((item) => item.swift === undefined),
    ...cases
      .filter((item) => item.swift !== undefined)
      .toSorted((a, b) => order.indexOf(a.swift) - order.indexOf(b.swift)),
  ];
  const lines = [`public enum ${name}: Codable, Sendable, Equatable {`];
  for (const item of cases)
    lines.push(item.swift === undefined ? `  case ${escape(item.name)}` : `  case ${escape(item.name)}(${item.swift})`);
  lines.push(
    "",
    "  public init(from decoder: any Decoder) throws {",
    "    let container = try decoder.singleValueContainer()",
  );
  tried.forEach((item, index) => {
    const lead = index === 0 ? "    if" : "    } else if";
    if (item.swift === undefined) {
      lines.push(
        `${lead} let value = try? container.decode(String.self), value == ${literal(item.value)} {`,
        `      self = .${escape(item.name)}`,
      );
    } else {
      lines.push(
        `${lead} let value = try? container.decode(${item.swift}.self) {`,
        `      self = .${escape(item.name)}(value)`,
      );
    }
  });
  lines.push(
    "    } else {",
    `      throw DecodingError.dataCorruptedError(in: container, debugDescription: "no member of ${name} matches")`,
    "    }",
    "  }",
    "",
    "  public func encode(to encoder: any Encoder) throws {",
    "    var container = encoder.singleValueContainer()",
    "    switch self {",
    ...cases.map((item) =>
      item.swift === undefined
        ? `    case .${escape(item.name)}: try container.encode(${literal(item.value)})`
        : `    case .${escape(item.name)}(let value): try container.encode(value)`,
    ),
    "    }",
    "  }",
    "}",
  );
  return lines;
}

/**
 * Refuses a union whose members would get the same case name.
 *
 * @remarks
 * Two cases with one name would not compile, and the message would not say why.
 *
 * @sideEffects none
 * @param {Array<{ name: string, path: string }>} cases - The cases.
 * @throws {Error} At the second member with a name already taken.
 */
function assertDistinct(cases) {
  const seen = new Set();
  for (const item of cases) {
    if (seen.has(item.name)) throw fail(item.path, `two members are both case ${item.name}`);
    seen.add(item.name);
  }
}

/**
 * Lists the object schemas a union member can be, looking through references and nested unions.
 *
 * @remarks
 * A member that is itself a union (`Command` in `ClientMessage`) is dispatched on all its members'
 * values at once.
 *
 * @sideEffects none
 * @param {any} ctx - The run.
 * @param {{ schema: any, path: string }} member - The member.
 * @returns {Array<{ schema: any, path: string }>} The objects.
 * @throws {Error} For a member that is not an object or a union of them.
 */
function variantsOf(ctx, member) {
  if (typeof member.schema.$ref === "string") {
    const ref = member.schema.$ref;
    const target = resolve(ctx, ref, member.path);
    check(target, `#/${ref}`);
    const key = target.anyOf === undefined ? "oneOf" : "anyOf";
    if (Array.isArray(target[key])) {
      return target[key].flatMap((inner, index) =>
        variantsOf(ctx, { schema: inner, path: `#/${ref}/${key}/${index}` }),
      );
    }
    if (target.type === "object" && !isRecord(target)) return [{ schema: target, path: `#/${ref}` }];
    throw fail(member.path, "unsupported union member");
  }
  if (member.schema.type === "object" && !isRecord(member.schema)) return [member];
  throw fail(member.path, "unsupported union member");
}

/**
 * Reads the values an object allows for a field, if the field is required and fixed.
 *
 * @remarks
 * A discriminating field is a constant, or a string enum when several values share one shape.
 *
 * @sideEffects none
 * @param {{ schema: any }} variant - The object.
 * @param {string} key - The field.
 * @returns {Array<string | boolean> | null} The values, or `null` when the field is not fixed.
 */
function fixedValues(variant, key) {
  const property = variant.schema.properties?.[key];
  if (property === undefined || !(variant.schema.required ?? []).includes(key)) return null;
  if (typeof property.const === "string" || typeof property.const === "boolean") return [property.const];
  if (property.type === "string" && Array.isArray(property.enum)) return property.enum;
  return null;
}

/**
 * Finds the field that tells a union's members apart, if there is one.
 *
 * @remarks
 * Every member must fix the field, with values of one kind and no value shared between members.
 * Fields are tried in the first member's order, so `Notice` (all `kind: "notice"`) is told apart
 * by `notice`, and `ResponseMessage` (all `type: "response"`) by `ok`.
 *
 * @sideEffects none
 * @param {any} ctx - The run.
 * @param {Array<{ schema: any, path: string }>} members - The members.
 * @returns {{ key: string, values: Array<Array<string | boolean>> } | null} The field and each
 *   member's values, or `null`.
 */
function findDiscriminator(ctx, members) {
  const groups = members.map((member) => variantsOf(ctx, member));
  const first = groups[0]?.[0];
  if (first === undefined) return null;
  for (const key of Object.keys(first.schema.properties ?? {})) {
    const values = groups.map((variants) => {
      const each = variants.map((variant) => fixedValues(variant, key));
      return each.includes(null) ? null : [...new Set(each.flat())];
    });
    if (values.includes(null)) continue;
    const all = values.flat();
    if (new Set(all.map((value) => typeof value)).size !== 1 || new Set(all).size !== all.length) continue;
    return { key, values };
  }
  return null;
}

/**
 * Names the case for a value of the discriminating field.
 *
 * @remarks
 * Strings name themselves; booleans need a name from `caseNames`, since `true` says nothing.
 *
 * @sideEffects none
 * @param {any} ctx - The run.
 * @param {string} union - The union's name.
 * @param {string} key - The discriminating field.
 * @param {string | boolean} value - The value.
 * @param {string} path - The member's place.
 * @returns {string} The case name.
 * @throws {Error} For a boolean without a name.
 */
function caseNameFor(ctx, union, key, value, path) {
  if (typeof value === "string") return camel(value, path);
  const name = ctx.caseNames[union]?.[String(value)];
  if (name === undefined) throw fail(path, `name the case for ${key} = ${value} in caseNames["${union}"]`);
  return name;
}

/**
 * Lists an inline object's constant fields as key and Swift literal.
 *
 * @remarks
 * A member with only constant fields becomes a case without a value; its constants are checked
 * and written by the union.
 *
 * @sideEffects none
 * @param {{ schema: any, path: string }} member - The member.
 * @returns {Array<{ key: string, value: string }>} The constants.
 */
function constantsOf(member) {
  return Object.entries(member.schema.properties ?? {})
    .filter(([, property]) => "const" in property)
    .map(([key, property]) => ({ key, value: constant(property.const, `${member.path}/properties/${key}`) }));
}

/**
 * Tells whether an inline object has fields that are not constant, besides `except`.
 *
 * @remarks
 * Such a member needs a nested `struct` for its values.
 *
 * @sideEffects none
 * @param {{ schema: any }} member - The member.
 * @param {string} [except] - A field not to count.
 * @returns {boolean} Whether it has such fields.
 */
function hasValues(member, except) {
  return Object.entries(member.schema.properties ?? {}).some(
    ([key, property]) => key !== except && !("const" in property),
  );
}

/**
 * Writes a union told apart by a discriminating field.
 *
 * @remarks
 * Decoding reads the field first and hands the whole object to the member it names; an unknown
 * value fails with the field and value.
 *
 * @sideEffects none
 * @param {any} ctx - The run.
 * @param {string} name - The type's name.
 * @param {Array<{ schema: any, path: string }>} members - The members.
 * @param {{ key: string, values: Array<Array<string | boolean>> }} discriminator - From `findDiscriminator`.
 * @param {Set<string>} ancestors - The enclosing types' names.
 * @returns {string[]} The declaration's lines.
 * @throws {Error} For a member with several values and other fields, or clashing case names.
 */
function declareTagged(ctx, name, members, discriminator, ancestors) {
  const scope = newScope(new Set([...ancestors, name]));
  const { key } = discriminator;
  const cases = [];
  members.forEach((member, index) => {
    const values = discriminator.values[index] ?? [];
    if (typeof member.schema.$ref === "string") {
      const ref = member.schema.$ref;
      const target = stripNull(resolve(ctx, ref, member.path), member.path).schema;
      const union = target.anyOf !== undefined || target.oneOf !== undefined;
      const [only] = values;
      const caseName =
        union || values.length !== 1 || only === undefined
          ? lowerFirst(ref)
          : caseNameFor(ctx, name, key, only, member.path);
      cases.push({ name: caseName, type: ref, values, path: member.path });
      return;
    }
    if (!hasValues(member, key)) {
      const others = constantsOf(member).filter((item) => item.key !== key);
      for (const value of values) {
        const written = typeof value === "string" ? literal(value) : String(value);
        cases.push({
          name: caseNameFor(ctx, name, key, value, member.path),
          values: [value],
          checks: others,
          writes: [{ key, value: written }, ...others],
          path: member.path,
        });
      }
      return;
    }
    const [only] = values;
    if (values.length !== 1 || only === undefined) {
      throw fail(member.path, `a member with several values of ${key} must have no other fields`);
    }
    const caseName = caseNameFor(ctx, name, key, only, member.path);
    const typeName = nestedName(ctx, scope, upperFirst(caseName));
    scope.nested.push(declareStruct(ctx, typeName, member.schema, member.path, scope.ancestors));
    cases.push({ name: caseName, type: typeName, values, path: member.path });
  });
  assertDistinct(cases);
  const all = cases.flatMap((item) => item.values);
  const boolean = typeof all[0] === "boolean";
  const exhaustive = boolean && all.includes(true) && all.includes(false);
  const lines = enumHead(name, cases, scope);
  lines.push(
    "  public init(from decoder: any Decoder) throws {",
    "    let container = try decoder.container(keyedBy: AnyKey.self)",
    `    switch try container.decode(${boolean ? "Bool" : "String"}.self, forKey: ${literal(key)}) {`,
  );
  for (const item of cases) {
    const labels = item.values.map((value) => (typeof value === "string" ? literal(value) : String(value))).join(", ");
    if (item.type !== undefined) {
      lines.push(`    case ${labels}: self = .${escape(item.name)}(try ${item.type}(from: decoder))`);
    } else if (item.checks.length === 0) {
      lines.push(`    case ${labels}: self = .${escape(item.name)}`);
    } else {
      lines.push(
        `    case ${labels}:`,
        ...item.checks.map((rule) => `      try container.expect(${literal(rule.key)}, ${rule.value})`),
        `      self = .${escape(item.name)}`,
      );
    }
  }
  if (!exhaustive) {
    lines.push(
      `    case let other: try container.unknown(${literal(key)}, ${boolean ? "String(other)" : "other"}, in: ${literal(name)})`,
    );
  }
  lines.push("    }", "  }", "", ...enumEncode(cases), "}");
  return lines;
}

/**
 * Writes a union of objects told apart by a key only one member has.
 *
 * @remarks
 * `InteractionAnswer` (`value`, `confirmed` or `cancelled`) and `QuestionReply` have no
 * discriminating field.
 *
 * @sideEffects none
 * @param {any} ctx - The run.
 * @param {string} name - The type's name.
 * @param {Array<{ schema: any, path: string }>} members - The members.
 * @param {string} path - The union's place.
 * @param {Set<string>} ancestors - The enclosing types' names.
 * @returns {string[]} The declaration's lines.
 * @throws {Error} When a member has no key of its own.
 */
function declareUntagged(ctx, name, members, path, ancestors) {
  const scope = newScope(new Set([...ancestors, name]));
  const variants = members.map((member) => {
    const found = variantsOf(ctx, member);
    const [only] = found;
    if (found.length !== 1 || only === undefined) throw fail(member.path, "unsupported nested union");
    return only;
  });
  const cases = members.map((member, index) => {
    const own = (variants[index]?.schema.required ?? []).find((key) =>
      variants.every((variant, other) => other === index || !(key in (variant.schema.properties ?? {}))),
    );
    if (own === undefined) throw fail(path, "no discriminator and no key only one member has");
    const caseName = camel(own, member.path);
    if (typeof member.schema.$ref === "string")
      return { name: caseName, type: member.schema.$ref, own, path: member.path };
    if (!hasValues(member)) {
      const constants = constantsOf(member);
      return { name: caseName, own, checks: constants, writes: constants, path: member.path };
    }
    const typeName = nestedName(ctx, scope, upperFirst(caseName));
    scope.nested.push(declareStruct(ctx, typeName, member.schema, member.path, scope.ancestors));
    return { name: caseName, type: typeName, own, path: member.path };
  });
  assertDistinct(cases);
  const lines = enumHead(name, cases, scope);
  lines.push(
    "  public init(from decoder: any Decoder) throws {",
    "    let container = try decoder.container(keyedBy: AnyKey.self)",
  );
  cases.forEach((item, index) => {
    lines.push(`    ${index === 0 ? "if" : "} else if"} container.contains(${literal(item.own)}) {`);
    if (item.type === undefined) {
      lines.push(
        ...item.checks.map((rule) => `      try container.expect(${literal(rule.key)}, ${rule.value})`),
        `      self = .${escape(item.name)}`,
      );
    } else {
      lines.push(`      self = .${escape(item.name)}(try ${item.type}(from: decoder))`);
    }
  });
  lines.push(
    "    } else {",
    `      try container.noMember(of: ${literal(name)})`,
    "    }",
    "  }",
    "",
    ...enumEncode(cases),
    "}",
  );
  return lines;
}

/**
 * Writes a union enum's first line, its cases and its nested types.
 *
 * @remarks
 * Shared by both kinds of object union.
 *
 * @sideEffects none
 * @param {string} name - The type's name.
 * @param {Array<{ name: string, type?: string }>} cases - The cases.
 * @param {{ nested: string[][] }} scope - The nested types.
 * @returns {string[]} The lines so far.
 */
function enumHead(name, cases, scope) {
  const lines = [`public enum ${name}: Codable, Sendable, Equatable {`];
  for (const item of cases)
    lines.push(item.type === undefined ? `  case ${escape(item.name)}` : `  case ${escape(item.name)}(${item.type})`);
  lines.push("");
  for (const block of scope.nested) lines.push(...indent(block), "");
  return lines;
}

/**
 * Writes a union enum's `encode(to:)`.
 *
 * @remarks
 * A case with a value encodes it whole (its struct writes the constants); a case without one
 * writes its constants itself.
 *
 * @sideEffects none
 * @param {Array<{ name: string, type?: string, writes?: Array<{ key: string, value: string }> }>} cases - The cases.
 * @returns {string[]} The method's lines.
 */
function enumEncode(cases) {
  const lines = ["  public func encode(to encoder: any Encoder) throws {", "    switch self {"];
  for (const item of cases) {
    if (item.type !== undefined) {
      lines.push(`    case .${escape(item.name)}(let value): try value.encode(to: encoder)`);
    } else {
      lines.push(
        `    case .${escape(item.name)}:`,
        "      var container = encoder.container(keyedBy: AnyKey.self)",
        ...(item.writes ?? []).map(
          (write) => `      try container.encode(${write.value}, forKey: ${literal(write.key)})`,
        ),
      );
    }
  }
  lines.push("    }", "  }");
  return lines;
}

/**
 * Indents lines by one level (two spaces), leaving blank lines blank.
 *
 * @remarks
 * Nested types are written at the top level and then indented into their parent.
 *
 * @sideEffects none
 * @param {string[]} lines - The lines.
 * @returns {string[]} The lines indented.
 */
function indent(lines) {
  return lines.flatMap((line) => line.split("\n")).map((line) => (line === "" ? "" : `  ${line}`));
}

/**
 * Turns a JSON value or key into a lower camel case Swift name.
 *
 * @remarks
 * `too_large` → `tooLarge`, `openai-codex` → `openaiCodex`, `1x` → `v1x`; names that are
 * already camel case stay as they are.
 *
 * @sideEffects none
 * @param {string} value - The text.
 * @param {string} path - Where it is, for the error.
 * @returns {string} The name, not yet escaped.
 * @throws {Error} When the text has no letters or digits.
 */
function camel(value, path) {
  const [head, ...rest] = value.split(/[^A-Za-z0-9]+/u).filter((part) => part !== "");
  if (head === undefined) throw fail(path, `cannot name a case for ${JSON.stringify(value)}`);
  const first = /[A-Z]/u.test(head) && head === head.toUpperCase() ? head.toLowerCase() : lowerFirst(head);
  const name = first + rest.map(upperFirst).join("");
  return /^[0-9]/u.test(name) ? `v${name}` : name;
}

/**
 * Upper-cases the first letter.
 *
 * @remarks
 * Type names from field and case names.
 *
 * @sideEffects none
 * @param {string} text - The text.
 * @returns {string} The text with its first letter in upper case.
 */
function upperFirst(text) {
  return text.slice(0, 1).toUpperCase() + text.slice(1);
}

/**
 * Lower-cases the first letter.
 *
 * @remarks
 * Case names from type names (`Command` → `command`).
 *
 * @sideEffects none
 * @param {string} text - The text.
 * @returns {string} The text with its first letter in lower case.
 */
function lowerFirst(text) {
  return text.slice(0, 1).toLowerCase() + text.slice(1);
}

/**
 * Escapes a Swift keyword used as a name.
 *
 * @remarks
 * A field called `default` must be written `` `default` ``.
 *
 * @sideEffects none
 * @param {string} name - The name.
 * @returns {string} It, in backticks if it is a keyword.
 */
function escape(name) {
  return KEYWORDS.has(name) ? `\`${name}\`` : name;
}

/**
 * Writes text as a Swift string literal.
 *
 * @remarks
 * JSON's `\uXXXX` is not Swift's `\u{X}`, so control characters are escaped here.
 *
 * @sideEffects none
 * @param {string} text - The text.
 * @returns {string} The literal.
 */
function literal(text) {
  // oxlint-disable-next-line no-control-regex -- control characters are exactly what must be escaped.
  const body = text.replaceAll(/[\\"\u0000-\u001f\u007f]/gu, (char) =>
    char === "\\" || char === '"' ? `\\${char}` : `\\u{${(char.codePointAt(0) ?? 0).toString(16)}}`,
  );
  return `"${body}"`;
}
